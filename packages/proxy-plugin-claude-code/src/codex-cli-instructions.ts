/** 默认的 instructions 模板（包含占位符 GPT-5.2） */
const CODEX_CLI_INSTRUCTIONS_TEMPLATE = Buffer.from(
  CODEX_CLI_INSTRUCTIONS_B64.replace(/\s+/g, ""),
  "base64"
).toString("utf8");

/** 默认模型名称占位符 */
const DEFAULT_MODEL_PLACEHOLDER = "GPT-5.2";

/**
 * 获取 Codex CLI instructions，支持动态模型名称
 * @param modelName - 目标模型名称，会被转换为大写并替换到 instructions 中
 */
export function getCodexCliInstructions(modelName?: string): string {
  if (!modelName) {
    return CODEX_CLI_INSTRUCTIONS_TEMPLATE;
  }

  // 将模型名称转换为大写格式（如 "gpt-5.2" -> "GPT-5.2"）
  const formattedModelName = modelName.toUpperCase();

  return CODEX_CLI_INSTRUCTIONS_TEMPLATE.replace(
    DEFAULT_MODEL_PLACEHOLDER,
    formattedModelName
  );
}

/**
 * 兼容旧代码的默认导出（使用默认 GPT-5.2）
 * @deprecated 请使用 getCodexCliInstructions(modelName) 代替
 */
